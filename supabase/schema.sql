create extension if not exists pgcrypto with schema extensions;

create table if not exists public.orders (
  id          bigint generated by default as identity (start with 1001) primary key,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz,
  student     text not null,
  grade       text not null,
  phone       text not null,
  size        text not null,
  jacket_name text not null,
  number      text not null default '28',
  status      text not null default 'new' check (status in ('new','approved','edit','cancelled'))
);
create index if not exists orders_phone_idx on public.orders (phone);

create table if not exists public.app_settings (
  id         int primary key default 1 check (id = 1),
  data       jsonb not null default '{}'::jsonb,
  admin_hash text
);

-- لا أحد يصل للجدولين مباشرة؛ كل شيء عبر الدوال أدناه فقط
alter table public.orders        enable row level security;
alter table public.app_settings  enable row level security;
revoke all on public.orders, public.app_settings from anon, authenticated;

